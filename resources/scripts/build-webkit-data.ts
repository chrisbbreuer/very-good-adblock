/**
 * Writes resources/functions/webkit-data.ts: the blocker's rules, cosmetic
 * selectors and page scripts as one TypeScript module, so the `very-good-adblock`
 * library (resources/functions/webkit.ts) carries everything a WebKit browser
 * needs with no files beside the code. Run after the rules or scripts change;
 * test/webkit.test.ts fails while the module is stale.
 *
 * Usage: bun --bun resources/scripts/build-webkit-data.ts [--check]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import generated from '../../src/rules/generated/network-hosts.json'
import { navigationHosts } from '../../src/rules/navigation'
import { curatedRuleSeeds } from '../../src/rules/static-rules'
import { consentCosmetic, genericCosmetic, twitchCosmetic, xCosmetic, youtubeCosmetic } from '../../src/shared/cosmetic'
import extension from '../../config/extension'

const root = join(import.meta.dir, '../..')
export const outFile: string = join(root, 'resources/functions/webkit-data.ts')

/** The extension's MAIN-world content scripts, bundled to one self-contained script each. */
async function pageScripts() {
  const entries = (extension.content ?? []).filter((script: any) => script.world === 'MAIN')
  const scripts = []
  for (const entry of entries) {
    const result = await Bun.build({ entrypoints: [join(root, entry.entry)], format: 'iife', minify: true, target: 'browser' })
    if (!result.success) throw new AggregateError(result.logs, `Could not bundle ${entry.entry}`)
    const hosts = (entry.matches as string[]).some(match => match.includes('://*/'))
      ? []
      : [...new Set((entry.matches as string[]).map(match => match.replace(/^[^:]+:\/\/(\*\.)?/, '').replace(/\/.*$/, '')))]
    scripts.push({ id: entry.entry.replace(/^src\/content\//, '').replace(/\.ts$/, ''), hosts, allFrames: entry.allFrames === true, js: (await result.outputs[0]!.text()).trim() })
  }
  return scripts
}

export async function render(): Promise<string> {
  const group = (value: { default: readonly string[], aggressive: readonly string[] }) => ({ default: [...value.default], aggressive: [...value.aggressive] })
  const data = {
    generatedAt: generated.generatedAt,
    blockedHosts: generated.hosts,
    curated: curatedRuleSeeds.map(seed => ({ name: seed.name, urlFilter: seed.urlFilter, resourceTypes: seed.resourceTypes as string[] })),
    navigationHosts,
    cosmetic: {
      generic: group(genericCosmetic),
      youtube: group(youtubeCosmetic),
      twitch: group(twitchCosmetic),
      x: group(xCosmetic),
      consent: group(consentCosmetic),
    },
    pageScripts: await pageScripts(),
  }
  return `// Generated by resources/scripts/build-webkit-data.ts from src/ — do not edit.\n/* eslint-disable */\nimport type { WebKitData } from './webkit'\n\nexport const data: WebKitData = ${JSON.stringify(data)}\n`
}

if (import.meta.main) {
  const next = await render()
  if (process.argv.includes('--check')) {
    const stale = readFileSync(outFile, 'utf8') !== next
    console.log(stale ? 'webkit-data.ts is stale: run bun --bun resources/scripts/build-webkit-data.ts' : 'webkit-data.ts is current')
    process.exit(stale ? 1 : 0)
  }
  writeFileSync(outFile, next)
  console.log(`Wrote ${outFile} (${(next.length / 1024).toFixed(0)} KB)`)
}
